namespace
{
    const juce::Identifier editorWidthProp { "editorWidth" }, editorHeightProp { "editorHeight" };
}

void AudioPluginAudioProcessor::setEditorSize (int width, int height) noexcept
{
    editorWidth = juce::jlimit (EditorSize::minWidth, EditorSize::maxWidth, width);
    editorHeight = juce::jlimit (EditorSize::minHeight, EditorSize::maxHeight, height);
}

void AudioPluginAudioProcessor::getStateInformation (juce::MemoryBlock& destData)
{
    auto state = apvts.copyState();
    presetManager.addPresetInfoTo (state);
    state.setProperty (editorWidthProp, editorWidth.load(), nullptr);
    state.setProperty (editorHeightProp, editorHeight.load(), nullptr);

    if (const auto xml = state.createXml())
        copyXmlToBinary (*xml, destData);
}

void AudioPluginAudioProcessor::setStateInformation (const void* data, int sizeInBytes)
{
    const auto xml = getXmlFromBinary (data, sizeInBytes);

    if (xml == nullptr || ! xml->hasTagName (apvts.state.getType()))
        return;

    auto state = juce::ValueTree::fromXml (*xml);

    if (state.hasProperty (editorWidthProp) && state.hasProperty (editorHeightProp))
        setEditorSize (state[editorWidthProp], state[editorHeightProp]);

    // Not left on the parameters' state, where a saved preset would pick it up
    state.removeProperty (editorWidthProp, nullptr);
    state.removeProperty (editorHeightProp, nullptr);

    presetManager.restoreState (state);
}

